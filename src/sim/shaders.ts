/* physically based sky: Rayleigh + Mie single scattering, Chapman sun transmittance */
export const GLSL_ATMOS = [
  "const float ATM_R = 6371000.0;",
  "const float ATM_TOP = 6471000.0;",
  "const vec3 B_R = vec3(5.8e-6, 13.5e-6, 33.1e-6);",
  "const float B_M = 21e-6;",
  "const float B_ME = 23.1e-6;",
  "const float H_R = 8000.0;",
  "const float H_M = 1200.0;",
  "const vec3 B_O = vec3(0.65e-6, 1.881e-6, 0.085e-6);",
  "float ozoneD(float h){ return max(0.0, 1.0 - abs(h - 25000.0) / 15000.0); }",
  "vec2 rsi(vec3 ro, vec3 rd, float r){",
  "  float L = length(ro); float b = dot(ro, rd); float c = (L - r) * (L + r); float d = b * b - c;",
  "  if (d < 0.0) return vec2(1e12, -1e12);",
  "  float sd = sqrt(d); float q = b < 0.0 ? (-b + sd) : (-b - sd);",
  "  if (abs(q) < 1e-6) q = 1e-6;",
  "  float x0 = q; float x1 = c / q;",
  "  return vec2(min(x0, x1), max(x0, x1));",
  "}",
  "float chapman(float X, float h, float c){",
  "  float cc = sqrt(X + h);",
  "  if (c >= 0.0) return cc / (cc * c + 1.0) * exp(-h);",
  "  float x0 = sqrt(max(1.0 - c * c, 0.0)) * (X + h);",
  "  if (x0 < X) return 1e7;",
  "  return 2.0 * sqrt(x0) * exp(X - x0) - cc / (1.0 - cc * c) * exp(-h);",
  "}",
  "vec3 sunTrans(vec3 pos, vec3 L){",
  "  float r = length(pos); float h = max(r - ATM_R, 0.0); float mu = dot(pos, L) / r;",
  "  float odR = H_R * chapman(ATM_R / H_R, h / H_R, mu);",
  "  float odM = H_M * chapman(ATM_R / H_M, h / H_M, mu);",
  "  float cz = sqrt(max(1.0 - (r * r) / (6396000.0 * 6396000.0) * (1.0 - mu * mu), 0.0));",
  "  float odO = (r < 6411000.0 || mu < 0.0) ? 15000.0 / max(cz, 0.035) : 0.0;",
  "  return exp(-(B_R * odR + B_ME * odM + B_O * odO));",
  "}",
  "void atmos(vec3 ro, vec3 rd, float tMax, vec3 L, out vec3 ins, out vec3 tr){",
  "  ins = vec3(0.0); tr = vec3(1.0);",
  "  vec2 ta = rsi(ro, rd, ATM_TOP);",
  "  if (ta.x > ta.y || ta.y < 0.0) return;",
  "  float t0 = max(ta.x, 0.0); float t1 = min(ta.y, tMax);",
  "  if (t1 <= t0) return;",
  "  float mu = dot(rd, L); float mumu = mu * mu;",
  "  float pR = 0.0596831 * (1.0 + mumu);",
  "  float pM = 0.1193662 * (0.4224 * (1.0 + mumu)) / (pow(max(1.5776 - 1.52 * mu, 1e-4), 1.5) * 2.5776);",
  "  float odR = 0.0; float odM = 0.0; float odO = 0.0; vec3 sR = vec3(0.0); vec3 sM = vec3(0.0);",
  "  for (int i = 0; i < ATM_STEPS; i++){",
  "    float f0 = float(i) / float(ATM_STEPS); float f1 = float(i + 1) / float(ATM_STEPS);",
  "    float sa = t0 + (t1 - t0) * f0 * f0; float sb = t0 + (t1 - t0) * f1 * f1; float ds = sb - sa;",
  "    vec3 pos = ro + rd * (0.5 * (sa + sb));",
  "    float h = max(length(pos) - ATM_R, 0.0);",
  "    float dR = exp(-h / H_R) * ds; float dM = exp(-h / H_M) * ds; float dO = ozoneD(h) * ds;",
  "    odR += dR; odM += dM; odO += dO;",
  "    vec3 att = exp(-(B_R * (odR - 0.5 * dR) + B_ME * (odM - 0.5 * dM) + B_O * (odO - 0.5 * dO))) * sunTrans(pos, L);",
  "    sR += dR * att; sM += dM * att;",
  "  }",
  "  ins = sR * B_R * pR + sM * B_M * pM;",
  "  tr = exp(-(B_R * odR + B_ME * odM + B_O * odO));",
  "}",
].join("\n");

