  "float fbm4(vec3 p){ float s = 0.0; float a = 0.5; for (int i = 0; i < 4; i++){ s += a * snoise(p); p = p * 2.02 + vec3(3.1, 1.7, 4.3); a *= 0.5; } return s; }",
  "float fbm7(vec3 p){ float s = 0.0; float a = 0.5; for (int i = 0; i < 7; i++){ s += a * snoise(p); p = p * 2.03 + vec3(1.3, 4.7, 2.9); a *= 0.5; } return s; }",
  "float ridge5(vec3 p){ float s = 0.0; float a = 0.5; for (int i = 0; i < 5; i++){ float n = 1.0 - abs(snoise(p)); s += a * n * n; p = p * 2.1 + vec3(2.3, 0.7, 5.1); a *= 0.5; } return s; }",
